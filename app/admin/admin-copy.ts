export const adminCopy: Record<Language, AdminCopy> = { en, fr, ar };

export const ADMIN_LANGUAGE_KEY = "tabletap:admin-language";

/** Saved choice first, then the phone's language, then English. */
export function initialAdminLanguage(): Language {
  try {
    const saved = localStorage.getItem(ADMIN_LANGUAGE_KEY);
    if (saved === "en" || saved === "fr" || saved === "ar") return saved;
  } catch {}
  const preferred = (navigator.languages ?? [navigator.language]).map((tag) =>
    tag.slice(0, 2).toLowerCase(),
  );
  return (preferred.find(
    (tag) => tag === "fr" || tag === "ar" || tag === "en",
  ) ?? "en") as Language;
}

export const AdminCopyContext = createContext<{
  t: AdminCopy;
  language: Language;
}>({
  t: en,
  language: "en",
});

export function useAdminCopy() {
  return useContext(AdminCopyContext);
}
